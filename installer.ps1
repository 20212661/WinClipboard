# WinClipboard per-user installer (no admin required).
#
# Usage:
#   powershell -NoProfile -ExecutionPolicy Bypass -File installer.ps1
#   installer.ps1 -InstallDir D:\apps\wclb -NoDesktop -Version 1.0.0
#
# What it does:
#   1. stops a running WinClipboard.exe (file locks)
#   2. mirrors dist\WinClipboard -> InstallDir (default %LOCALAPPDATA%\Programs\WinClipboard)
#   3. creates Start Menu + Desktop shortcuts (opt out with -NoStartMenu / -NoDesktop)
#   4. writes an uninstall.ps1 into InstallDir
#   5. registers a per-user "Add/Remove Programs" entry pointing at that uninstaller
#
# Build the app first with:  打包构建.bat  (needs dist\WinClipboard\WinClipboard.exe)
# Keep this file pure ASCII (PowerShell 5.1 reads no-BOM scripts as ANSI).

param(
    [string]$InstallDir = "$env:LOCALAPPDATA\Programs\WinClipboard",
    [switch]$NoDesktop,
    [switch]$NoStartMenu,
    [string]$Version = "1.0.0",
    # non-empty => registry key gets a suffix (used by automated tests)
    [string]$RegSuffix = ""
)

$ErrorActionPreference = "Stop"
$src = Join-Path $PSScriptRoot "dist\WinClipboard"
if (-not (Test-Path (Join-Path $src "WinClipboard.exe"))) {
    Write-Host "[ERROR] dist\WinClipboard\WinClipboard.exe not found. Run the build script first." -ForegroundColor Red
    exit 1
}

$running = Get-Process WinClipboard -ErrorAction SilentlyContinue
if ($running) {
    Write-Host "Stopping running WinClipboard..."
    $running | Stop-Process -Force
    Start-Sleep -Milliseconds 800
}

Write-Host "Installing to $InstallDir ..."
New-Item -ItemType Directory -Force -Path $InstallDir | Out-Null
robocopy $src $InstallDir /MIR /NFL /NDL /NJH /NJS | Out-Null
if ($LASTEXITCODE -ge 8) {
    Write-Host "[ERROR] file copy failed (robocopy code $LASTEXITCODE)" -ForegroundColor Red
    exit 1
}

$exe = Join-Path $InstallDir "WinClipboard.exe"
$ws = New-Object -ComObject WScript.Shell

function Make-Shortcut([string]$path) {
    $lnk = $ws.CreateShortcut($path)
    $lnk.TargetPath = $exe
    $lnk.WorkingDirectory = $InstallDir
    $lnk.Description = "WinClipboard clipboard manager"
    $lnk.Save()
}

if (-not $NoStartMenu) {
    $sm = Join-Path ([Environment]::GetFolderPath("StartMenu")) "Programs\WinClipboard.lnk"
    Make-Shortcut $sm
    Write-Host "Start menu shortcut: $sm"
}
if (-not $NoDesktop) {
    $dt = Join-Path ([Environment]::GetFolderPath("Desktop")) "WinClipboard.lnk"
    Make-Shortcut $dt
    Write-Host "Desktop shortcut: $dt"
}

# Generated uninstaller: removes app + shortcuts + registry entry.
# User data (%APPDATA%\WinClipboard: history/config/private) is kept on purpose.
# Single-quoted here-string: content is fully literal, no escaping games.
$uninst = Join-Path $InstallDir "uninstall.ps1"
@'
# WinClipboard uninstaller (generated by installer.ps1 - do not edit)
param([string]$RegSuffix = "")
$ErrorActionPreference = "Stop"
Get-Process WinClipboard -ErrorAction SilentlyContinue | Stop-Process -Force
Start-Sleep -Milliseconds 600
Remove-Item (Join-Path ([Environment]::GetFolderPath("StartMenu")) "Programs\WinClipboard.lnk") -Force -ErrorAction SilentlyContinue
Remove-Item (Join-Path ([Environment]::GetFolderPath("Desktop")) "WinClipboard.lnk") -Force -ErrorAction SilentlyContinue
Remove-Item "HKCU:\Software\Microsoft\Windows\CurrentVersion\Uninstall\WinClipboard$RegSuffix" -Recurse -Force -ErrorAction SilentlyContinue
Remove-Item $PSScriptRoot -Recurse -Force
Write-Host "WinClipboard uninstalled. User data kept at %APPDATA%\WinClipboard."
'@ | Set-Content -Path $uninst -Encoding ASCII

$reg = "HKCU:\Software\Microsoft\Windows\CurrentVersion\Uninstall\WinClipboard$RegSuffix"
New-Item -Path $reg -Force | Out-Null
$size = (Get-ChildItem $InstallDir -Recurse -File | Measure-Object Length -Sum).Sum
$props = @{
    DisplayName     = "WinClipboard"
    DisplayVersion  = $Version
    Publisher       = "haoshangyang"
    InstallLocation = $InstallDir
    DisplayIcon     = $exe
    UninstallString = "powershell.exe -NoProfile -ExecutionPolicy Bypass -File `"$uninst`""
    NoModify        = 1
    NoRepair        = 1
    EstimatedSize   = [int]($size / 1KB)
}
foreach ($k in $props.Keys) {
    New-ItemProperty -Path $reg -Name $k -Value $props[$k] -PropertyType String -Force | Out-Null
}

Write-Host ""
Write-Host "Installed WinClipboard v$Version"
Write-Host "  App:        $exe"
Write-Host "  Uninstall:  Settings > Apps (or uninstall.ps1)"
Write-Host "  User data:  %APPDATA%\WinClipboard (kept on uninstall)"
